const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
const { renderHomeCreations } = require('../src/views/planetaboricua/home-creations');
const home = require('../src/views/planetaboricua');
const image = 'https://res.cloudinary.com/demo/image/upload/pieza.jpg';
const records = Array.from({length:6},(_,i)=>({slug:'taller-'+i,name:'Taller '+i,city:'Hatillo',email:'private@example.com',gallery:[{image,title:'Pieza '+i,description:'Trabajo artesanal.'}]}));
const day = new Date('2026-11-05T12:00:00Z');
const html = renderHomeCreations(records,day);
assert.equal((html.match(/class="home-creation"/g)||[]).length,4);
assert.doesNotMatch(html,/private@example|undefined|NaN/);
assert.match(html,/#artisan-gallery-title/);
assert.notEqual(html,renderHomeCreations(records,new Date('2026-11-06T12:00:00Z')),'A daily selection gives other artisans visibility');
assert.equal(html,renderHomeCreations([...records,records[0]],day),'Duplicate records must not take extra slots');
const malicious = [{slug:'../../pb-control',gallery:records[0].gallery},{slug:'unsafe-image',gallery:[{image:'javascript:alert(1)',title:'X',description:'X'}]},{slug:'legacy',gallery:[image]}];
assert.doesNotMatch(renderHomeCreations(malicious,day),/home-creations-grid|javascript:|pb-control/);
assert.match(renderHomeCreations([{...records[0],name:'<script>private</script>',gallery:[{image,title:'<img onerror=alert(1)>',description:'Test'}]}],day),/&lt;img/);
assert.doesNotMatch(renderHomeCreations([],day),/Cargando|undefined/);
assert.equal((home.match(/id="latest-grid"/g)||[]).length,1);
assert.equal((home.match(/Crea tu espacio digital gratis/g)||[]).length,1);
for (const [first,second] of [['id="hero"','id="feria"'],['id="feria"','id="agenda"'],['id="agenda"','id="articulos"'],['id="articulos"','id="recursos"'],['id="recursos"','id="viajes"']]) assert.ok(home.indexOf(first)<home.indexOf(second));
assert.match(home,/const events=\(data.events\|\|\[\]\)\.slice\(0,3\)/);
const scripts = [...home.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/gi)].map(m=>m[1]);
for (const script of scripts) assert.doesNotThrow(()=>new vm.Script(script),'Inline JavaScript must compile after template interpolation');
// Exercise the actual independent feeds: the blog must not overwrite news.
const elements = new Map();
const element = id => {if (!elements.has(id)) elements.set(id,{innerHTML:'',textContent:'',href:'',outerHTML:''});return elements.get(id)};
const pending=[];
const context = {document:{getElementById:element},console,Date,encodeURIComponent,pbCheckForUpdate(){},fetch:async url=>({json:async()=>url.includes('pb-lo-mas-reciente')?{items:[{slug:'noticia',title:'Noticia',summary:'Actualidad',publishedAt:day}]}:[{title:'Historia',img:image,link:'/blog/historia'},{title:'Segunda',img:image,link:'/blog/segunda'}]})};
(async()=>{
  const hydrated=scripts.find(s=>s.includes('// Blog Feed'));
  const start=hydrated.indexOf('// Lo más reciente —');
  const end=hydrated.indexOf('setInterval',start);
  vm.runInNewContext(hydrated.slice(start,end),context);
  await new Promise(resolve=>setImmediate(resolve));
  assert.match(element('latest-grid').innerHTML,/Noticia/);
  assert.equal(element('hero-main-title').textContent,'Historia');
  assert.match(element('noticias-grid').innerHTML,/Segunda/);
  assert.equal(element('hero-sidebar').innerHTML,'','Blog feed must leave the news sidebar intact');
  console.log('PB homepage: selection, privacy, escaping, section order and independent feed hydration passed');
})().catch(error=>{console.error(error);process.exitCode=1});
